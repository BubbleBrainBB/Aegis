// Bundles the design component runtime (src/ui/design-runtime) with React into
// src/shared/design-runtime-bundle.ts, a string the board frames inline: they
// have no network and no app origin to load scripts from. The output is
// committed; `--check` fails when it is stale (verify:design runs it).
import { build } from "esbuild";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const outfile = join(root, "src/shared/design-runtime-bundle.ts");

const result = await build({
  entryPoints: [join(root, "src/ui/design-runtime/runtime.ts")],
  bundle: true,
  write: false,
  format: "iife",
  platform: "browser",
  target: "chrome120",
  minify: true,
  legalComments: "none",
  define: { "process.env.NODE_ENV": '"production"' },
  logLevel: "warning",
});
// Inline in <script>: no `</script` may end the element early.
const code = result.outputFiles[0].text.trim().replace(/<\/(script)/gi, "<\\/$1");
const source = `// Generated by scripts/build-design-runtime.mjs from src/ui/design-runtime. Do not edit.\n// React ${JSON.parse(readFileSync(join(root, "node_modules/react/package.json"), "utf8")).version}, production build.\nexport const DESIGN_RUNTIME_SCRIPT = ${JSON.stringify(code)};\n`;

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(outfile, "utf8");
  } catch {}
  if (current !== source) {
    console.error("src/shared/design-runtime-bundle.ts is stale: run node scripts/build-design-runtime.mjs");
    process.exit(1);
  }
  console.log("design runtime bundle is current");
} else {
  writeFileSync(outfile, source);
  console.log(`design runtime: ${(code.length / 1024).toFixed(0)} KB`);
}
