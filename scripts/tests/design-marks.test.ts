import assert from "node:assert/strict";
import { createDesignMark, markFromPoints, markPath, markArrowHead, moveDesignMarkEndpoint, resizeDesignMark, styleDesignMark, translateDesignMark } from "../../src/ui/components/design/design-marks";
import { normalizeDesignMark, normalizeDesignMarks, validateDesignMarks, MAX_MARK_POINTS, MAX_MARK_TEXT } from "../../src/shared/design-marks";

const arrow = createDesignMark("arrow", { x: 200, y: 50 }, { x: 20, y: -10 }, "arrow");
assert.equal(arrow.x, 20); assert.equal(arrow.y, -10);
assert.deepEqual(arrow.points, [{ x: 180, y: 60 }, { x: 0, y: 0 }]);
assert.match(markPath(arrow), /^M180,60 L0,0$/);
assert.ok(markArrowHead(arrow)?.includes(" 0,0 "), "arrow head stays at the original drag endpoint");
const restored = normalizeDesignMarks(JSON.parse(JSON.stringify([arrow])));
assert.deepEqual(restored, [arrow], "round trip retains ordered endpoints");
const moved = translateDesignMark(arrow, 5, -8);
assert.deepEqual(moved.points, arrow.points); assert.equal(moved.x, 25); assert.equal(moved.y, -18);
const resized = resizeDesignMark(arrow, "nw", -180, -60);
assert.deepEqual(resized.points, [{ x: 360, y: 120 }, { x: 0, y: 0 }]);
assert.equal(resized.x + resized.width, arrow.x + arrow.width);
assert.equal(resized.y + resized.height, arrow.y + arrow.height);
const note = createDesignMark("note", { x: 0, y: 0 }, undefined, "note", "page-2");
assert.equal(note.width, 240); assert.equal(note.pageId, "page-2");
const smaller = resizeDesignMark(note, "nw", 10000, 10000);
assert.equal(smaller.width, 80); assert.equal(smaller.height, 40);
assert.equal(smaller.x + smaller.width, 240); assert.equal(smaller.y + smaller.height, 180);
const square = createDesignMark("rectangle", { x: 10, y: 20 }, { x: 110, y: 70 }, "rect");
const locked = resizeDesignMark(square, "se", 50, 0, true);
assert.equal(locked.width / locked.height, 2);
const free = markFromPoints(Array.from({ length: 10000 }, (_, i) => ({ x: i / 10, y: i % 4 })), "pen");
assert.ok(free); assert.ok(free.points!.length <= MAX_MARK_POINTS);
assert.equal(free.points![0].x, 0); assert.equal(free.points!.at(-1)?.x, 999.9);
assert.ok(markPath(free).includes(" Q")); assert.equal(markFromPoints([{ x: 0, y: 0 }], "single"), null);
assert.equal(normalizeDesignMark({ ...note, x: Infinity }), null);
assert.equal(normalizeDesignMark({ ...note, width: -1 }), null);
assert.equal(normalizeDesignMark({ ...arrow, points: [{ x: NaN, y: 0 }, { x: 3, y: 0 }] }), null);
assert.equal(normalizeDesignMark({ ...arrow, points: Array(MAX_MARK_POINTS + 1).fill({ x: 0, y: 0 }) }), null);
assert.equal(normalizeDesignMark({ ...note, fill: "url(https://example.com/leak)" })?.fill, "#fff3b0");
assert.equal(normalizeDesignMark({ ...note, text: "x".repeat(MAX_MARK_TEXT + 1) })?.text?.length, MAX_MARK_TEXT);
assert.deepEqual(normalizeDesignMarks([note, { ...note, text: "duplicate" }, null]), [note]);
assert.equal(normalizeDesignMarks(Array.from({ length: 300 }, (_, i) => ({ ...note, id: `n${i}` }))).length, 200);
assert.deepEqual(validateDesignMarks([note, arrow, free]), [note, arrow, free]);
for (const raw of [null, {}, [note, note], [{ ...note, x: 1_000_001 }], [{ ...note, width: 8001 }], [{ ...note, fill: "url(https://example.com)" }], [{ ...note, text: "x".repeat(MAX_MARK_TEXT + 1) }], [{ ...arrow, points: [{ x: -1, y: 0 }, { x: 1, y: 1 }] }], Array.from({ length: 201 }, (_, i) => ({ ...note, id: `n${i}` }))]) assert.throws(() => validateDesignMarks(raw), "writes reject invalid input instead of silently losing objects");
const endpoints = (mark: typeof arrow) => mark.points!.map(point => ({ x: mark.x + point.x, y: mark.y + point.y }));
const initialEndpoints = endpoints(arrow);
const endMoved = moveDesignMarkEndpoint(arrow, 1, 300, 100);
assert.deepEqual(endpoints(endMoved), [initialEndpoints[0], { x: 320, y: 90 }], "crossing the start keeps ordered arrow direction and anchors the start");
assert.equal(endMoved.type, "arrow");
assert.deepEqual(endpoints(moveDesignMarkEndpoint(arrow, 0, -250, 30)), [{ x: -50, y: 80 }, initialEndpoints[1]], "moving start anchors the end");
const collapsed = moveDesignMarkEndpoint(arrow, 1, 180, 60);
assert.deepEqual(endpoints(collapsed), [initialEndpoints[0], initialEndpoints[0]]);
assert.equal(collapsed.width, 1); assert.equal(collapsed.height, 1);
const reopened = moveDesignMarkEndpoint(collapsed, 1, 0, 90);
assert.deepEqual(endpoints(reopened), [initialEndpoints[0], { x: 200, y: 140 }], "a collapsed line can be reopened vertically");
const constrained = moveDesignMarkEndpoint(arrow, 1, 300, 125, true), [fixed, snapped] = endpoints(constrained);
assert.deepEqual(fixed, initialEndpoints[0]);
assert.ok(Math.abs(Math.abs(snapped.x - fixed.x) - Math.abs(snapped.y - fixed.y)) < .02, "Shift snaps to 45 degrees");
const huge = moveDesignMarkEndpoint(arrow, 1, 40000, 20000);
assert.deepEqual(endpoints(huge)[0], initialEndpoints[0]);
assert.ok(huge.width <= 8000 && huge.height <= 8000);
assert.deepEqual(validateDesignMarks([endMoved, { ...collapsed, id: "collapsed" }, { ...huge, id: "huge" }]).map(endpoints), [endpoints(endMoved), endpoints(collapsed), endpoints(huge)], "endpoint edits retain coordinates through persistence");
assert.strictEqual(moveDesignMarkEndpoint(note, 0, 5, 5), note);
assert.strictEqual(moveDesignMarkEndpoint(arrow, 0, NaN, 5), arrow);
const filled = styleDesignMark(square, "fill", "#d97757");
assert.equal(filled.fill, "#d97757"); assert.equal(filled.x, square.x); assert.equal(filled.width, square.width);
const thickArrow = styleDesignMark(arrow, "strokeWidth", 8);
assert.equal(thickArrow.strokeWidth, 8); assert.deepEqual(thickArrow.points, arrow.points);
assert.equal(styleDesignMark(free, "stroke", "#4a8c5c").stroke, "#4a8c5c");
assert.strictEqual(styleDesignMark(free, "fill", "#ffffff"), free, "open paths have no inert fill control");
assert.strictEqual(styleDesignMark(square, "stroke", "url(https://example.com)"), square);
assert.strictEqual(styleDesignMark(square, "stroke", "#123456"), square, "UI palette is bounded");
assert.strictEqual(styleDesignMark(arrow, "strokeWidth", 65), arrow);
console.log("design marks: geometry, serialization, endpoint direction, bounded input passed");
